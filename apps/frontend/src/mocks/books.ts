/** Project a full book down to the list/card shape. */
export function toSummary(book: BookDetail): BookSummary {
  return {
    id: book.id,
    title: book.title,
    author: book.author ?? 'Unknown',
    series: book.series,
    genres: book.genres,
    rating: book.rating,
    numRatings: book.numRatings,
    publishYear: book.publishYear,
    coverImg: book.coverImg,
  };
}

